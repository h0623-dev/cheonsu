import assert from 'node:assert/strict';
import { applyEquipmentStats, applyEquipmentToParty, grantExp, makeAlly, mergePartyFromUnits, mergePartyIntoStage, syncBattleSkillMastery } from '../src/engine/partyEngine.js';
import { createDefeatCheckpoint } from '../src/engine/campaignProgress.js';
import { applyRecruitStartingGrowth } from '../src/engine/recruitmentEngine.js';
import { stages } from '../src/data/stages.js';
import { EQUIPMENT } from '../src/data/equipment.js';

const ally = { id: 'hero', type: 'ally', name: '카일', level: 1, exp: 0, maxHp: 20, hp: 9, atk: 8, def: 5, equipment: {}, skillLevel: 0 };
const base = applyEquipmentStats(makeAlly(ally));
const boosted = { ...base, atk: 11, def: 12, itemPowerBoost: 3, itemGuardBoost: 3, skillGuardBoost: 4, guard: true };
const earned = grantExp([boosted], 'hero', 1).units[0];
assert.equal(earned.atk, 11);
assert.equal(earned.def, 12);
const leveled = grantExp([boosted], 'hero', 100).units[0];
assert.equal(leveled.atk, 12);
assert.equal(leveled.def, 13);
const clean = applyEquipmentToParty([earned])[0];
assert.equal(clean.atk, 8);
assert.equal(clean.def, 5);
for (const flag of ['itemPowerBoost', 'itemGuardBoost', 'skillGuardBoost']) assert.equal(clean[flag], 0);
assert.equal(clean.guard, false);
for (const stage of stages.filter(stage => stage.id >= 11 && stage.id <= 50)) {
  const next = mergePartyIntoStage(stage, [earned]).find(unit => unit.id === 'hero');
  assert.equal(next.atk, 8, `stage ${stage.id} attack reset`);
  assert.equal(next.def, 5, `stage ${stage.id} defense reset`);
  assert.equal(next.itemPowerBoost, 0);
  assert.equal(next.itemGuardBoost, 0);
}
const gear = Object.values(EQUIPMENT).find(item => item.atk > 0);
const equipment = { [gear.slot]: gear.id };
const old = { ...boosted, equipment, gearEnhance: { [gear.id]: 2 }, atk: 8 + gear.atk + 2 + 3, def: 5 + gear.def + (gear.def > 0 ? 2 : 0) + 7 };
delete old.baseAtk; delete old.baseDef;
const recovered = makeAlly(old);
assert.equal(recovered.baseAtk, 8);
assert.equal(recovered.baseDef, 5);
assert.deepEqual(makeAlly(recovered), recovered);
const oldCamp = applyEquipmentToParty([old])[0];
assert.equal(oldCamp.atk, 8 + gear.atk + 2);
assert.equal(oldCamp.def, 5 + gear.def + (gear.def > 0 ? 2 : 0));
const retreat = createDefeatCheckpoint({ selectedStage: { id: 11 }, party: [base], units: [], clearedStages: [], gold: 100 }, { party: [old] }).checkpoint.party[0];
assert.equal(retreat.atk, oldCamp.atk);
assert.equal(retreat.def, oldCamp.def);
assert.equal(retreat.hp, 20);
assert.equal(retreat.itemPowerBoost, 0);
const selected = makeAlly({ ...ally, activeSkillId: 'oath', skillType: 'attack', skillRange: 9, skillBonus: 42, skillCooldown: 7 });
assert.equal(selected.skillType, 'guard');
assert.equal(selected.skillRange, 0);
assert.equal(selected.skillBonus, 42);
assert.equal(selected.skillCooldown, 7);
const ledger = syncBattleSkillMastery([base], [{ ...boosted, skillLevel: 1, hp: 0, status: ['burn'] }], 'hero');
assert.equal(ledger[0].skillLevel, 1);
assert.equal(ledger[0].hp, base.hp);
assert.equal(ledger[0].itemPowerBoost, undefined);
assert.equal(mergePartyFromUnits(ledger, [])[0].skillLevel, 1);
assert.equal(syncBattleSkillMastery(ledger, [{ ...base, skillLevel: 0 }], 'hero')[0].skillLevel, 1);
assert.equal(syncBattleSkillMastery(ledger, [{ ...base, skillLevel: 99 }], 'hero')[0].skillLevel, 3);
assert.equal(syncBattleSkillMastery(ledger, [{ ...base, skillLevel: NaN }], 'hero'), ledger);
const recruit = applyRecruitStartingGrowth(old, [{ ...base, level: 10 }]);
assert.equal(recruit.level, 7);
assert.equal(recruit.baseAtk, 14);
assert.equal(recruit.baseDef, 11);
