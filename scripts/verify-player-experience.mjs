import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const base = process.env.GAME_URL || 'http://127.0.0.1:5176';
const key = 'cheonsu_v01_save';
const out = 'tmp/player-experience-qa';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: process.env.CHEONSU_QA_BROWSER || 'msedge', headless: true });
const reports = [];
try {
  for (const viewport of [{ width: 1280, height: 900 }, { width: 390, height: 844 }, { width: 320, height: 568 }, { width: 844, height: 390 }, { width: 568, height: 320 }]) {
    const page = await browser.newPage({ viewport, serviceWorkers: 'block', reducedMotion: 'reduce' });
    page.setDefaultTimeout(12000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const button = name => page.getByRole('button', { name, exact: true });
    const saved = () => page.evaluate(key => localStorage.getItem(key), key);
    const capture = async name => {
      await page.screenshot({ path: `${out}/${viewport.width}-${name}.png` });
      const overflow = await page.evaluate(() => [...document.querySelectorAll('.ux-screen,.journey-title,.ux-page-header,.ux-tabs,.journey-title-actions,.company-details,.library-replay-actions')].filter(el => el.scrollWidth > el.clientWidth + 2).map(el => el.className));
      assert.deepEqual(overflow, [], name);
    };
    try {
      await page.addInitScript(() => {
        if (!localStorage.getItem('cheonsu_settings_v1')) localStorage.setItem('cheonsu_settings_v1', JSON.stringify({ soundOn: false, musicOn: false, cutsceneMode: 'off' }));
      });
      await page.goto(base);
      await page.locator('.journey-title-art').evaluate(img => img.decode());
      await capture('title');
      assert.equal(await button('이어하기').count(), 0);
      await button('설정').click();
      await button('저장').click();
      assert.ok(await button('현재 상태 저장').isDisabled());
      assert.ok(await button('슬롯 1 저장').isDisabled());
      await button('뒤로').click();
      await button('새 게임').click();
      await page.locator('.campaign-header .prominent-save').click();
      await page.locator('.campaign-continue-band').getByRole('button').click();
      await page.locator('.deployment-management > summary').click();
      await page.locator('.chapter-brief').waitFor();
      await capture('deployment');
      await page.reload();
      await button('이어하기').click();
      await page.locator('.campaign-header').getByRole('button', { name: '마을', exact: true }).click();
      await page.locator('.town-player-nav').getByRole('button', { name: '기사단', exact: true }).click();
      await button('리나 선택').click();
      assert.match(await page.locator('.company-identity').innerText(), /화염 궁수/);
      assert.equal(await page.locator('.company-skills article').count(), 2);
      await page.locator('.company-character').evaluate(img => img.decode());
      await capture('roster');
      await button('장비 관리').click();
      assert.equal(await page.getByRole('tab', { name: '리나 장비', exact: true }).getAttribute('aria-selected'), 'true');
      await button('시설 닫기').click();
      await page.locator('.town-player-nav').getByRole('button', { name: '설정', exact: true }).click();
      await capture('settings');
      await button('전투').click();
      await button('3배속').click();
      assert.equal(await button('3배속').getAttribute('aria-pressed'), 'true');
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('cheonsu_settings_v1')).battleSpeed), 'turbo');
      await button('저장').click();
      await button('현재 상태 저장').click();
      assert.equal(JSON.parse(await saved()).screen, 'camp');
      await button('슬롯 1 저장').click();
      assert.equal(await button('슬롯 1 불러오기').isDisabled(), false);
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('cheonsu_v01_manual_slot_1')).screen), 'camp');
      await capture('saves');
      await button('뒤로').click();
      await page.locator('.town-player-nav').getByRole('button', { name: '기록실', exact: true }).click();
      assert.ok(await button('1장 전투 후 이야기').isDisabled());
      assert.ok(await button('2장 전투 전 이야기').isDisabled());
      await capture('library');
      const beforeReplay = await saved();
      await button('1장 전투 전 이야기').click();
      const first = await page.locator('.narrative-line').innerText();
      await page.clock.install();
      await button('자동 진행').click();
      await page.clock.runFor(9500);
      assert.notEqual(await page.locator('.narrative-line').innerText(), first);
      await button('대화 기록').click();
      const paused = await page.locator('.narrative-line').innerText();
      await page.clock.runFor(10000);
      assert.equal(await page.locator('.narrative-line').innerText(), paused);
      await button('대화 기록 닫기').click();
      await button('자동 진행 중지').click();
      await page.clock.resume();
      await page.locator('.narrative-header').getByRole('button', { name: '기록실로', exact: true }).click();
      assert.equal(await saved(), beforeReplay, 'replay must not change save, rewards or selected stage');
      await button('도감·기록').click();
      await button('도감').click();
      await page.locator('.codex-screen').waitFor();
      await button('뒤로').click();
      await page.locator('.journey-library').waitFor();
      await button('뒤로').click();
      await page.locator('.camp-screen').waitFor();
      await page.locator('.camp-header').getByRole('button', { name: '메뉴', exact: true }).click();
      await button('새 게임').click();
      await page.getByRole('dialog').getByRole('button', { name: '돌아가기', exact: true }).click();
      assert.equal(await saved(), beforeReplay);
      await page.reload();
      await capture('resume');
      await button('설정').click();
      await button('저장').click();
      assert.ok(await button('현재 상태 저장').isDisabled());
      await button('슬롯 2 저장').click();
      assert.equal(await saved(), beforeReplay, 'title settings must not overwrite existing checkpoint');
      assert.equal(await page.evaluate(() => localStorage.getItem('cheonsu_v01_manual_slot_2')), beforeReplay);
      await button('뒤로').click();
      await button('기록실').click();
      await button('도감·기록').click();
      assert.match(await page.locator('.library-checkpoint').innerText(), /저장된 여정/);
      await button('이어하기').click();
      await page.locator('.camp-screen').waitFor();
      await page.evaluate(key => {
        const data = JSON.parse(localStorage.getItem(key)); data.clearedStages = [1, 2];
        localStorage.setItem(key, JSON.stringify(data));
      }, key);
      await page.reload();
      const beforeClearReplay = await saved();
      await button('기록실').click();
      assert.ok(await button('3장 전투 후 이야기').isDisabled());
      assert.ok(await button('4장 전투 전 이야기').isDisabled());
      assert.equal(await button('3장 전투 전 이야기').isDisabled(), false);
      await button('2장 전투 후 이야기').click();
      while (await button('다음').count()) await button('다음').click();
      await page.locator('.narrative-dialogue').getByRole('button', { name: '기록실로', exact: true }).click();
      await page.locator('.journey-library').waitFor();
      assert.equal(await saved(), beforeClearReplay, 'post-battle replay must not grant clear rewards');
      await button('뒤로').click();
      await button('설정').click();
      await button('저장').click();
      await page.locator('.ux-danger summary').click();
      page.on('dialog', dialog => dialog.accept());
      await button('수동 슬롯 비우기').click();
      assert.ok(await button('슬롯 1 불러오기').isDisabled());
      assert.ok(await button('슬롯 2 불러오기').isDisabled());
      assert.equal(await saved(), beforeClearReplay);
      await button('현재 저장 데이터 초기화').click();
      assert.equal(await saved(), null);
      await button('설정').click();
      await button('저장').click();
      assert.ok(await button('현재 상태 저장').isDisabled());
      assert.ok(await button('슬롯 1 저장').isDisabled());
      assert.deepEqual(errors, []);
      reports.push({ ...viewport, passed: true });
      console.log(`PASS player experience ${viewport.width}x${viewport.height}: menus, settings, roster, saves, replay isolation`);
    } catch (error) {
      await page.screenshot({ path: `${out}/failure-${viewport.width}.png` }).catch(() => {});
      await fs.writeFile(`${out}/failure-${viewport.width}.txt`, `${error.stack}\n${await page.locator('body').innerText()}`);
      throw error;
    } finally { await page.close(); }
  }
} finally {
  await browser.close();
  await fs.writeFile(`${out}/report.json`, JSON.stringify(reports, null, 2));
}
